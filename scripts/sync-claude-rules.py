#!/usr/bin/env python3
"""Generate per-directory AGENTS.md files from .claude/rules/*.instructions.md.

Vibe Code only loads files named AGENTS.md into the agent context. Claude Code
loads .claude/rules/*.instructions.md and applies them when the edited file
matches the rule's applyTo glob. To give Vibe Code the same conventions, this
script generates one AGENTS.md per target directory (repo root, backend/,
frontend/, docs/), each containing the rules whose applyTo globs match that
directory. Generated files are committed so every Vibe session picks them up
automatically.

Usage:
    python3 scripts/sync-claude-rules.py           # regenerate and exit 0/1
    python3 scripts/sync-claude-rules.py --check   # CI mode: fail if drifted
"""

from __future__ import annotations

import argparse
import fnmatch
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = REPO_ROOT / ".claude" / "rules"

HEADER = "<!-- Generated by scripts/sync-claude-rules.py from .claude/rules/. Do not edit manually. -->"

BEGIN_MARKER = "<!-- BEGIN GENERATED RULES (scripts/sync-claude-rules.py) -->"
END_MARKER = "<!-- END GENERATED RULES -->"

# Fully generated per-directory files. The root AGENTS.md is hand-maintained:
# only the section between BEGIN_MARKER and END_MARKER is regenerated.
GENERATED_TARGETS: dict[str, list[str]] = {
    "backend": ["backend/**", "backend/"],
    "frontend": ["frontend/**", "frontend/"],
    "docs": ["docs/**", "docs/"],
}

GLOBAL_RULES = {"**"}


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
    if not match:
        return {}, text
    frontmatter: dict[str, str] = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        frontmatter[key.strip()] = value.strip().strip("'\"")
    return frontmatter, match.group(2)


def rule_matches(apply_to: str, directory: str) -> bool:
    """A rule applies to a target directory when any of its comma-separated
    applyTo globs matches the directory itself, the repo-wide '**' glob, or a
    path prefix of the directory (e.g. 'backend/**/*.rs' covers backend/)."""
    dir_path = "" if directory == "." else directory
    for pattern in apply_to.split(","):
        pattern = pattern.strip()
        if not pattern:
            continue
        if pattern in GLOBAL_RULES:
            return True
        # 'backend/**/*.rs' -> matches anything under backend/
        if pattern.startswith(dir_path + "/") or (dir_path and pattern.startswith(dir_path)):
            return True
        # exact directory match or directory prefix match ('backend/src/**' vs 'backend')
        if dir_path and (pattern == dir_path or pattern.startswith(dir_path + "/")):
            return True
        if pattern.startswith("**/"):
            suffix = pattern[3:]
            if fnmatch.fnmatch(dir_path + "/", suffix) or fnmatch.fnmatch(dir_path, suffix):
                return True
    return False


def collect_rules(directory: str) -> list[tuple[str, str, str]]:
    """Return (filename, description, body) for rules matching the directory,
    sorted by filename for stable output."""
    rules: list[tuple[str, str, str]] = []
    for rule_file in sorted(RULES_DIR.glob("*.instructions.md")):
        frontmatter, body = parse_frontmatter(rule_file.read_text(encoding="utf-8"))
        apply_to = frontmatter.get("applyTo", "")
        if not apply_to or not rule_matches(apply_to, directory):
            continue
        description = frontmatter.get("description", "")
        rules.append((rule_file.name, description, body.strip()))
    return rules


def render_rules_section(rules: list[tuple[str, str, str]]) -> str:
    lines: list[str] = []
    for filename, description, body in rules:
        lines.append(f"## Rule: {filename.removesuffix('.instructions.md')}")
        lines.append("")
        if description:
            lines.append(f"_{description}_")
            lines.append("")
        lines.append(body)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render(directory: str, rules: list[tuple[str, str, str]]) -> str:
    rel = directory
    title = f"La Ruche — Agent Instructions ({rel}/)"
    lines = [
        HEADER,
        "",
        f"# {title}",
        "",
        f"Domain rules for `{rel}/`, mirrored from `.claude/rules/` "
        "(source of truth). Closer `AGENTS.md` files take priority over "
        "the repo-root one.\n",
        render_rules_section(rules),
    ]
    return "\n".join(lines).rstrip() + "\n"


def render_root_section(rules: list[tuple[str, str, str]]) -> str:
    lines = [
        BEGIN_MARKER,
        "",
        "## Project rules (mirrored from .claude/rules/)",
        "",
        "Project-wide rules from `.claude/rules/` are mirrored below. Domain "
        "rules for `backend/`, `frontend/` and `docs/` live in the `AGENTS.md` "
        "of each directory and take priority there.",
        "",
        render_rules_section(rules),
        END_MARKER,
    ]
    return "\n".join(lines).rstrip() + "\n"


def splice_root_agents_md(section: str) -> str:
    """Replace the generated block in the hand-maintained root AGENTS.md.

    If the markers are missing, append the generated block at the end of the
    file so the first run bootstraps it.
    """
    path = REPO_ROOT / "AGENTS.md"
    current = path.read_text(encoding="utf-8") if path.is_file() else ""
    if BEGIN_MARKER in current and END_MARKER in current:
        before, rest = current.split(BEGIN_MARKER, 1)
        _, after = rest.split(END_MARKER, 1)
        return before.rstrip() + "\n\n" + section + "\n" + after.lstrip("\n")
    base = current.rstrip() + "\n\n" if current.strip() else ""
    return base + section + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="only verify generated files are up to date (CI mode)",
    )
    args = parser.parse_args()

    if not RULES_DIR.is_dir():
        print(f"error: rules directory not found: {RULES_DIR}", file=sys.stderr)
        return 1

    drifted: list[str] = []

    root_section = render_root_section(collect_rules("."))
    root_content = splice_root_agents_md(root_section)
    root_md = REPO_ROOT / "AGENTS.md"
    if args.check:
        current = root_md.read_text(encoding="utf-8") if root_md.is_file() else None
        if current != root_content:
            drifted.append("AGENTS.md")
    else:
        root_md.write_text(root_content, encoding="utf-8")
        print("generated AGENTS.md (generated rules section)")

    for directory in GENERATED_TARGETS:
        target_dir = REPO_ROOT / directory
        target_dir.mkdir(parents=True, exist_ok=True)
        agents_md = target_dir / "AGENTS.md"
        content = render(directory, collect_rules(directory))
        if args.check:
            current = agents_md.read_text(encoding="utf-8") if agents_md.is_file() else None
            if current != content:
                drifted.append(str(agents_md.relative_to(REPO_ROOT)))
        else:
            agents_md.write_text(content, encoding="utf-8")
            print(f"generated {agents_md.relative_to(REPO_ROOT)}")

    if args.check:
        if drifted:
            print(
                "error: generated AGENTS.md files are out of sync with "
                ".claude/rules/. Run `python3 scripts/sync-claude-rules.py` "
                "and commit the result.\nDrifted files:\n  " + "\n  ".join(drifted),
                file=sys.stderr,
            )
            return 1
        print("AGENTS.md files are in sync with .claude/rules/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
